#!/bin/sh
#
# mkzipfile.sh — Embed a directory of files as a ZIP for the native server.
#
# Usage:  ./mkzipfile.sh <directory> [output]
#
# Zips all files in <directory> (without any path prefix) and writes:
#   archive.zip  — the raw ZIP bytes
#   zipdata.S    — assembler stub that .incbin's the ZIP (no C hex array)
#   zipdata.h    — extern declarations for zipdata / zipdata_end / zipdata_len
#
# [output] may be a directory, or a file path whose directory is used
# (historically zipdata.h). Default: current directory.
#
set -e

if [ $# -lt 1 ]; then
    echo "Usage: $0 <directory> [output_file_or_dir]" >&2
    exit 1
fi

SRCDIR="$1"
OUTPUT="${2:-.}"

if [ ! -d "$SRCDIR" ]; then
    echo "Error: '$SRCDIR' is not a directory" >&2
    exit 1
fi

if [ -d "$OUTPUT" ]; then
    OUTDIR="$OUTPUT"
else
    OUTDIR=$(dirname "$OUTPUT")
fi
mkdir -p "$OUTDIR"
OUTDIR=$(CDPATH= cd -- "$OUTDIR" && pwd)

ARCHIVE="$OUTDIR/archive.zip"
HEADER="$OUTDIR/zipdata.h"
ASMFILE="$OUTDIR/zipdata.S"

# Create a unique temp directory and place the zip archive inside it.
TMPDIR_MZ=$(mktemp -d /tmp/mkzipfile.XXXXXX)
TMPZIP="$TMPDIR_MZ/archive.zip"
trap 'rm -rf "$TMPDIR_MZ"' EXIT

# Zip all non-hidden files from inside the directory (no path prefix).
# Store already-compressed media uncompressed (-n) so the native server can
# serve large files with zero-copy / cheap HTTP Range responses. Deflating
# MP4/JPEG typically saves almost nothing but forces a full malloc+inflate
# per request, which exhausts memory on iOS after repeated media loads.
(cd "$SRCDIR" && find . -type f ! -name '.*' -print | sed 's|^\./||' | \
    zip -n '.mp4:.MP4:.jpg:.JPG:.jpeg:.JPEG:.png:.PNG:.webp:.ttf:.woff:.woff2' -@ "$TMPZIP") > /dev/null

# Guard: never ship 0-byte entries for non-empty source files, and require
# media extensions to be ZIP stored (method 0) so zero-copy serving works.
python3 - "$SRCDIR" "$TMPZIP" <<'PY'
import sys, zipfile
from pathlib import Path
srcdir, zippath = Path(sys.argv[1]), Path(sys.argv[2])
bad = []
deflated_media = []
media_ext = {'.mp4', '.jpg', '.jpeg', '.png', '.webp', '.ttf', '.woff', '.woff2'}
with zipfile.ZipFile(zippath) as z:
    for info in z.infolist():
        if info.is_dir():
            continue
        src = srcdir / info.filename
        if not src.is_file():
            continue
        disk = src.stat().st_size
        if disk > 0 and info.file_size == 0:
            bad.append((info.filename, disk))
        ext = Path(info.filename).suffix.lower()
        if ext in media_ext and info.compress_type != zipfile.ZIP_STORED:
            deflated_media.append(info.filename)
if bad:
    print("mkzipfile: ERROR — zip stored empty data for non-empty files:", file=sys.stderr)
    for name, disk in bad[:30]:
        print(f"  {name} (disk {disk} bytes, zip 0)", file=sys.stderr)
    if len(bad) > 30:
        print(f"  ... and {len(bad) - 30} more", file=sys.stderr)
    sys.exit(1)
if deflated_media:
    print("mkzipfile: ERROR — media should be ZIP stored (method 0), not deflated:", file=sys.stderr)
    for name in deflated_media[:20]:
        print(f"  {name}", file=sys.stderr)
    sys.exit(1)
n = sum(1 for i in zipfile.ZipFile(zippath).infolist() if not i.is_dir())
print(f"mkzipfile: zip content check OK ({n} entries, media stored uncompressed)")
PY

cp "$TMPZIP" "$ARCHIVE"

# Tiny C header — the ZIP itself is never parsed as C source.
cat > "$HEADER" << 'EOF'
/* Generated by mkzipfile.sh — do not edit */
#ifndef PASSIFLORA_ZIPDATA_H
#define PASSIFLORA_ZIPDATA_H

#include <stddef.h>

#ifdef __cplusplus
extern "C" {
#endif

extern const unsigned char zipdata[];
extern const unsigned char zipdata_end[];

#define zipdata_len ((size_t)(zipdata_end - zipdata))

#ifdef __cplusplus
}
#endif

#endif
EOF

# Assembler stub. .incbin is handled by the assembler, so Clang's C
# frontend never sees the archive bytes (which is what overflowed it
# when the ZIP was dumped as a hex array in a header).
cat > "$ASMFILE" << EOF
/* Generated by mkzipfile.sh — do not edit */
#if defined(__APPLE__)
	.const_data
	.globl _zipdata
	.p2align 4
_zipdata:
	.incbin "$ARCHIVE"
	.globl _zipdata_end
_zipdata_end:
#elif defined(_WIN32) || defined(__CYGWIN__) || defined(__MINGW32__)
	.section .rdata,"dr"
	.globl zipdata
	.align 16
zipdata:
	.incbin "$ARCHIVE"
	.globl zipdata_end
zipdata_end:
#else
	.section .rodata,"a"
	.globl zipdata
	.align 16
zipdata:
	.incbin "$ARCHIVE"
	.globl zipdata_end
zipdata_end:
#endif
EOF

echo "mkzipfile: $ARCHIVE generated ($(wc -c < "$TMPZIP" | tr -d ' ') bytes of ZIP data)"
